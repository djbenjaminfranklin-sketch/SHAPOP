export const FULFILLMENT_TEXTS: Record<'en' | 'fr' | 'es' | 'ru' | 'he', FulfillmentTexts> = { en, fr, es, ru, he }

export type FulfillmentTextKey = keyof FulfillmentTexts

/** Textes dans la langue courante (anglais par défaut si la langue n'est pas couverte). */
export function ft(lang: string = getLang()): FulfillmentTexts {
  return FULFILLMENT_TEXTS[lang as keyof typeof FULFILLMENT_TEXTS] || en
}

export function statusLabel(status: string | null | undefined, lang: string = getLang()): string {
  const t = ft(lang) as Record<string, string>
  return t[`status_${status}`] || String(status || '')
}

/** Message d'erreur serveur → texte lisible. */
export function errorText(code: string, lang: string = getLang()): string {
  const t = ft(lang) as Record<string, string>
  return t[code] || t.error_generic
}
