export type Lang = keyof typeof translations
export type TranslationKey = keyof typeof translations['fr']

export function t(lang: string, key: TranslationKey): string {
  const l = (lang in translations ? lang : 'fr') as Lang
  return translations[l][key] || translations.fr[key]
}

export function getLang(): Lang {
  const stored = localStorage.getItem('shapop_lang') as Lang | null
  if (stored && stored in translations) return stored
  // Auto-detect from device language
  const browserLang = navigator.language?.slice(0, 2)?.toLowerCase()
  if (browserLang && browserLang in translations) return browserLang as Lang
  return 'fr'
}

export function setLang(lang: Lang) {
  localStorage.setItem('shapop_lang', lang)
}
